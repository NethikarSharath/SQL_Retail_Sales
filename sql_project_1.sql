-- Q.7. W.A SQL QUERY TO CALCULATE THE AVERAGE SALE FOR EACH MONTH. 
-- FIND OUT THE BEST-SELLING MONTH IN EACH YEAR
SELECT 
		EXTRACT(YEAR FROM SALE_DATE) AS YEAR,
		EXTRACT(MONTH FROM SALE_DATE) AS MONTH,
		AVG(TOTAL_SALE) AS AVERAGE
FROM RETAIL_SALES_DB
GROUP BY 1,2
ORDER BY AVG(TOTAL_SALE) DESC
LIMIT 2;
-- OR 
SELECT 
	YEAR,
	MONTH,
	AVG_SALE
FROM
	(SELECT 
		EXTRACT(YEAR FROM SALE_DATE) AS YEAR,
		EXTRACT(MONTH FROM SALE_DATE) AS MONTH,
		AVG(TOTAL_SALE) AS AVG_SALE,
		RANK() OVER(PARTITION BY EXTRACT(YEAR FROM SALE_DATE) ORDER BY AVG(TOTAL_SALE) DESC) AS RANK_NO
	FROM RETAIL_SALES_DB
	GROUP BY 1,2) AS T1
WHERE RANK_NO = 1

-- Q.8 W.A SQL QUERY TO FIND TOP 5 CUSTOMERS BASED ON THE HIGHEST TOTAL SALES:
SELECT 
	CUSTOMER_ID,
	SUM(TOTAL_SALE) AS TOTAL_SALES
FROM RETAIL_SALES_DB
GROUP BY CUSTOMER_ID
ORDER BY SUM(TOTAL_SALE) DESC
LIMIT 5;

-- Q.9 W.A SQL QUERY TO FIND THE NUMBER OF UNIQUE CUSTOMERS WHO PURCHASED ITEMS FROM EACH CATEGORY
SELECT 
	CATEGORY,
	COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS
FROM RETAIL_SALES_DB
GROUP BY CATEGORY
ORDER BY 2 DESC;

-- Q.10 W.A SQL QUERY TO CREATE EACH SHIFT AND 
-- NUMBER OF ORDERS (EXAMPLE MORNING <= 12, AFTERNOON BETWEEN 12 AND 17, EVENING >17)
WITH Shift_Table AS(
	SELECT 
		*,
		CASE 
			WHEN EXTRACT(HOUR FROM SALE_TIME) < 12 THEN 'Morning'
			WHEN EXTRACT(HOUR FROM SALE_TIME) BETWEEN 12 AND 17 THEN 'Afternoon'
			ELSE 'Evening'
		END AS SHIFT_LOG
	FROM RETAIL_SALES_DB
	)
SELECT 
	SHIFT_LOG,
	COUNT(*)
FROM Shift_Table
GROUP BY SHIFT_LOG;