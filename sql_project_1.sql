-- Q.1 W.A SQL QUERY TO RETRIVE ALL THE COLUMNS FOR SALES MADE ON "2022-11-22":
SELECT * 
FROM RETAIL_SALES_DB
WHERE SALE_DATE = '2022-11-22'
ORDER BY SALE_TIME;

-- Q.2 W.A SQL QUERY TO RETRIVE ALL TRANSACTIONS WHERE THE CATEGORY IS "CLOTHING" AND THE QUANTITY SOLD 
--IS MORE THAN 10 IN THE MONTH OF NOVEMBER 2022
SELECT *
FROM RETAIL_SALES_DB
WHERE 
	category = 'Clothing' 
	AND quantity > 3 AND 
	sale_date BETWEEN '2022-11-01' AND '2022-11-30'
ORDER BY SALE_DATE;

-- Q.3 W.A SQL QUERY TO CALCULATE THE TOTAL SALES FOR EACH CATEGORY:
SELECT 
	CATEGORY,
	COUNT(CATEGORY) AS TOTAL_NO_OF_SALES,
	SUM(TOTAL_SALE) AS TOTAL_SUM_OF_SALES
FROM RETAIL_SALES_DB
GROUP BY CATEGORY;


-- Q.4 W.A SQL QUERY TO FIND THE AVERAGE AGE OF CUSTOMERS WHO 
-- PURCHASED ITEMS FROM THE "BEAUTY" CATEGORY
SELECT
	CATEGORY,
	COUNT(CATEGORY) AS NO_OF_PERSONS,
	ROUND(AVG(AGE),2) AS AVERAGE_AGE
FROM RETAIL_SALES_DB
GROUP BY CATEGORY
HAVING CATEGORY = 'Beauty'
-- OR
SELECT
	ROUND(AVG(AGE),2) AS AVERAGE_AGE
FROM RETAIL_SALES_DB
WHERE CATEGORY = 'Beauty'

-- Q.5 W.A SQL QUERY TO FIND ALL TRANSACTIONS WHERE THE TOTAL SALES IS GREATER THAN 1000
SELECT *
